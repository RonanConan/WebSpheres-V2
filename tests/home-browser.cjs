const { launch, serve, counter } = require('./harness.cjs');
const { openHost } = require('./host-page.cjs');
const { ok, done } = counter('HOME BROWSER');
const near = (a, b) => Math.abs(a - b) < 1e-6;
const L = { x: -0.2, y: 0.85, z: -0.35 }, R = { x: 0.25, y: 0.9, z: -0.3 };
const BL = { x: -0.2, y: 0.85, z: -0.33 }, BR = { x: 0.25, y: 0.9, z: -0.28 };
const same = (a, b) => near(a.x, b.x) && near(a.y, b.y) && near(a.z, b.z);

(async () => {
  const b = await launch(['--autoplay-policy=no-user-gesture-required']);
  let { p } = await openHost(b);
  const E = (fn, arg) => p.evaluate(fn, arg);
  const cmd = (name, value) => E(([n, v]) => window.__cmd(n, v), [name, value]);
  const state = () => E(() => window.__state());
  const hands = (l, r) => E(([a, c]) => { Object.assign(window.__hand.L, a); Object.assign(window.__hand.R, c); }, [l, r]);
  const idle = () => E(() => !window.__sm.activeSphere);
  const away = { x: 0, y: 0.2, z: 0.4 };
  const info = () => E(() => Object.fromEntries(window.__dm.buildSessionInfo().trim().split('\n').slice(1).map(l => l.split(','))));
  const cueText = () => E(() => document.querySelector('#participant-cue-text').getAttribute('value'));

  console.log('ONE BOX IS THE DEFAULT');
  ok((await state()).homeMode === 'one-box', 'state reports one-box');
  ok(await E(() => window.__sm.homeHalfWidth === 0.4 && window.__sm.homeRectangle.getAttribute('visible') !== false && !document.querySelector('#home-left').getAttribute('visible')), '80 cm box shown, hand boxes hidden');
  await cmd('cue', 'lap');
  ok(await cueText() === 'Rest both hands on your lap', 'one-box cue: hands on lap');
  await cmd('cue', null);
  await E(() => { window.__track('L', [-0.1, 0.8, -0.4]); window.__track('R', [0.1, 0.8, -0.4]); });
  await cmd('calibrate', 'lap');
  ok((await state()).calib.lap.done && !(await state()).calib.lap.left, 'one-box calibration has no hand boxes');

  console.log('CHOOSING ONE PER HAND');
  ok(!(await cmd('setHomeMode', 'sideways')).result.ok, 'unknown home position refused');
  let r = await cmd('setHomeMode', 'per-hand');
  ok(r.result.ok && r.next.homeMode === 'per-hand' && !r.next.calib.lap.done, 'switching clears home calibration, so the guide asks for it again');
  ok(await E(() => window.__sm.homeHalfWidth === 0.1 && window.__sm.homeRectangle.getAttribute('visible') === false), 'big box hidden, half width 10 cm');
  ok(await E(() => !document.querySelector('#home-left').getAttribute('visible') && !document.querySelector('#home-right').getAttribute('visible')), 'hand boxes hidden until calibrated');
  await cmd('cue', 'lap');
  ok(await cueText() === 'Rest both hands on your lap', 'per-hand cue: same wording');
  await cmd('cue', null);
  r = await cmd('setHomeMode', 'per-hand');
  ok(r.result.ok, 'choosing the same mode again is fine');

  console.log('CALIBRATING');
  await E(() => window.__track('R', null));
  r = await cmd('calibrate', 'lap');
  ok(!r.result.ok && r.result.reason === 'Both hands must be tracked' && !r.next.calib.lap.done, 'one hand lost: refused, nothing changes');
  await E(([l, c]) => { window.__track('L', [l.x, l.y, l.z]); window.__track('R', [c.x, c.y, c.z]); }, [L, R]);
  r = await cmd('calibrate', 'lap');
  const lap = r.next.calib.lap;
  ok(r.result.ok && lap.done && same(lap.left, BL) && same(lap.right, BR), 'each box placed at its own hand');
  ok(near(lap.home.x, 0.025) && near(lap.home.y, 0.875) && near(lap.home.z, -0.305), 'home value is the midpoint');
  ok(await E(() => document.querySelector('#home-left').getAttribute('visible') && document.querySelector('#home-right').getAttribute('visible')), 'hand boxes visible to the participant');
  ok(await E(([a, c]) => { const pl = document.querySelector('#home-left').getAttribute('position'), pr = document.querySelector('#home-right').getAttribute('position'); return Math.abs(pl.x - a.x) < 1e-6 && Math.abs(pr.x - c.x) < 1e-6 && Math.abs(pl.z - a.z) < 1e-6; }, [BL, BR]), 'hand boxes drawn where calibrated');

  console.log('TRIAL START RULE');
  await hands(away, away);
  await cmd('start');
  await p.waitForTimeout(250);
  ok(await idle(), 'hands away: no target');
  await hands(BR, BL);
  await p.waitForTimeout(250);
  ok(await idle(), 'hands crossed into the wrong boxes: no target');
  await hands({ x: 0, y: 0.875, z: -0.305 }, { x: 0, y: 0.875, z: -0.305 });
  await p.waitForTimeout(250);
  ok(await idle(), 'inside the old big box but outside each hand box: no target');
  await hands(BL, away);
  await p.waitForTimeout(250);
  ok(await idle(), 'left in its box, right away: no target');
  await hands(BL, BR);
  await p.waitForFunction(() => window.__sm.currentState === 'visible', null, { timeout: 3000, polling: 10 });
  ok(true, 'each hand in its own box: target appears');
  await p.waitForTimeout(60);
  await E(() => window.__hitLeft());
  await p.waitForFunction(() => window.__dm.trialNumber === 1, null, { timeout: 3000, polling: 10 });
  const trial = await E(() => window.__dm.trialData[0]);
  ok(trial.hand === 'LEFT' && trial.decisionTime > 0, `reach recorded, decision time measured from leaving the box (${trial.decisionTime} ms)`);

  console.log('LOCKED AFTER START');
  r = await cmd('setHomeMode', 'one-box');
  ok(!r.result.ok && r.result.reason === 'Setup locked. Unlock first.', 'locked during a session');
  await cmd('unlockSetup');
  r = await cmd('setHomeMode', 'one-box');
  ok(!r.result.ok && r.result.reason === 'Set the home position before starting the session.' && r.next.homeMode === 'per-hand', 'still refused after unlocking');

  console.log('DATA');
  const rows = await E(() => ({ L: window.__km.leftHandData.at(-1).split(','), R: window.__km.rightHandData.at(-1).split(',') }));
  ok(rows.L.length === 26 && rows.R.length === 26, 'kinematics rows keep 26 columns');
  ok(same({ x: +rows.L[4], y: +rows.L[5], z: +rows.L[6] }, BL), 'left file: home columns hold the left box');
  ok(same({ x: +rows.R[4], y: +rows.R[5], z: +rows.R[6] }, BR), 'right file: home columns hold the right box');
  const i = await info();
  ok(i.HomeMode === 'per-hand' && near(+i.HomeLeftX, BL.x) && near(+i.HomeLeftZ, BL.z) && near(+i.HomeRightX, BR.x) && near(+i.HomeRightY, BR.y), 'session info records mode and both boxes');
  ok(near(+i.HomeX, 0.025), 'existing HomeX key holds the midpoint');
  ok(p.errs.length === 0, 'no page errors (' + p.errs.join(' | ') + ')');

  console.log('ONE BOX DATA UNCHANGED');
  ({ p } = await openHost(b));
  await E(() => { window.__track('L', [-0.1, 0.8, -0.4]); window.__track('R', [0.1, 0.8, -0.4]); });
  await cmd('calibrate', 'lap');
  await cmd('start');
  await p.waitForTimeout(200);
  const one = await E(() => ({ L: window.__km.leftHandData.at(-1).split(','), R: window.__km.rightHandData.at(-1).split(','), box: window.__sm.homeRectangle.getAttribute('position') }));
  ok(one.L.slice(4, 7).join() === `${one.box.x},${one.box.y},${one.box.z}` && one.R.slice(4, 7).join() === one.L.slice(4, 7).join(), 'both files hold the single box');
  const i1 = await info();
  ok(i1.HomeMode === 'one-box' && i1.HomeLeftX === '' && i1.HomeRightZ === '', 'session info: mode one-box, hand box rows blank');

  console.log('OBSERVER');
  const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
  const o = await ctx.newPage();
  const errs = [];
  o.on('pageerror', e => errs.push(e.message));
  await serve(o);
  await o.clock.install();
  await o.goto('https://test.local/observer.html');
  await o.waitForFunction(() => window.__peers && window.__peers.length > 0 && window.__obs);
  await o.evaluate(() => {
    const P = window.__peers.at(-1); P.serverOpen(); const c = P.conns.at(-1); window.__c = c;
    const send = c.send.bind(c);
    c.send = (d) => { send(d); const m = JSON.parse(d); if (m.type === 'cmd') queueMicrotask(() => c.emit('data', JSON.stringify({ type: 'cmdResult', id: m.id, ok: true, reason: '' }))); };
    c.open = true; c.emit('open');
  });
  const O = (fn, arg) => o.evaluate(fn, arg);
  const tick = () => o.clock.runFor(300);
  const handAt = (h) => Array.from({ length: 75 }, (_, i) => [h.x, h.y, h.z][i % 3]);
  const BASE = { type: 'state', version: '2.8.0', phase: 'setup', endReason: '', participantId: 'P1', experimenter: 'Jo', homeMode: 'one-box', dominantHand: 'LEFT', condition: 1, mode: 'standard', totalTrials: 352, setupLocked: false, calib: { reach: { done: true, hand: 'LEFT', distance: 0.6, radius: 0.48 }, height: { done: true, height: 1 }, lap: { done: true, home: { x: 0, y: 0.9, z: -0.4 } } }, recentred: true, cue: null, sessionMs: 0, trialCount: 0, recentreCount: 0, pauses: 0, backup: { trials: 0, kinL: 0, kinR: 0, final: false, exportTs: '' }, info: '' };
  const emit = (m) => O((d) => window.__c.emit('data', JSON.stringify(d)), m);
  const frame = (l, c) => emit({ head: { px: 0, py: 1.2, pz: 0, qx: 0, qy: 0, qz: 0, qw: 1 }, left: handAt(l), right: handAt(c), leftValid: true, rightValid: true, activeSphere: -1, trialCount: 0, totalTrials: 352, homePos: { x: 0, y: 0.9, z: -0.4 } });
  const checks = (id) => O((i) => [...document.querySelectorAll('#' + i + ' li')].map(li => li.children[1].textContent), id);
  await emit(BASE); await tick();
  await O(() => document.querySelector('[data-open="3"]').click()); await tick();
  ok(await O(() => document.querySelector('[data-plan-home="one-box"]').classList.contains('on')), 'plan shows the mode the headset reports');
  ok(await O(() => document.querySelector('[data-plan-home="one-box"]').textContent === 'One box' && document.querySelector('[data-plan-home="per-hand"]').textContent === 'One per hand'), 'buttons read One box, One per hand');
  ok(await O(() => window.__obs.homeBox.visible && !window.__obs.homeBoxL.visible && !window.__obs.homeBoxR.visible), 'one box drawn in the 3D view');
  await o.click('[data-plan-home="per-hand"]');
  await o.click('#g-plan-send'); await tick();
  const cmds = await O(() => window.__c.sent.map(s => JSON.parse(s)).filter(m => m.type === 'cmd' && m.name !== 'cue').map(m => m.name));
  ok(cmds.join() === 'setMode,setHomeMode,setCondition,setPlan', 'Send to headset includes home position');
  const PER = Object.assign({}, BASE, { homeMode: 'per-hand', calib: Object.assign({}, BASE.calib, { lap: { done: true, home: { x: 0.025, y: 0.875, z: -0.305 }, left: BL, right: BR } }) });
  await emit(PER); await frame(BL, BR); await tick();
  ok(await O(() => !window.__obs.homeBox.visible && window.__obs.homeBoxL.visible && window.__obs.homeBoxR.visible), 'two boxes drawn, big box hidden');
  ok(await O(([a, c]) => { const l = window.__obs.homeBoxL.position, r = window.__obs.homeBoxR.position; return Math.abs(l.x - a.x) < 1e-6 && Math.abs(r.z - c.z) < 1e-6; }, [BL, BR]), 'boxes at the reported positions');
  await O(() => document.querySelector('[data-open="5"]').click()); await tick();
  let lines = await checks('g5-lap');
  ok(lines[0] === 'Left box at x -0.20, y 0.85, z -0.33 m' && lines[1] === 'Right box at x 0.25, y 0.90, z -0.28 m' && lines[2] === 'Both hands are in their home boxes.', 'calibrate step lists both boxes and the live check');
  await frame(BR, BL); await tick();
  lines = await checks('g5-lap');
  ok(lines[2] === 'Both hands are outside their home boxes.', 'crossed hands count as outside');
  await O(() => { window.__obs.settings.homeBox = false; document.querySelector('[data-setting="homeBox"]')?.click(); });
  await tick();
  ok(await O(() => !window.__obs.homeBoxL.visible && !window.__obs.homeBoxR.visible), 'Home box setting hides both');
  ok(errs.length === 0, 'no observer page errors (' + errs.join(' | ') + ')');

  await b.close();
  done();
})().catch(e => { console.error(e); process.exit(2); });
