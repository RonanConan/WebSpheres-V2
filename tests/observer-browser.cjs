const { serve, launch, counter } = require('./harness.cjs');
const { ok, done } = counter('OBSERVER BROWSER');
(async () => {
  const browser = await launch();
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errs = [];
  page.on('pageerror', e => errs.push(e.message));
  await serve(page);
  await page.clock.install();
  await page.goto('https://test.local/observer.html');
  await page.clock.runFor(1500);
  const E = (fn, arg) => page.evaluate(fn, arg);
  const txt = (id) => E((i) => document.getElementById(i).textContent, id);
  const st = () => txt('conn-state');
  const detail = () => txt('conn-detail');
  const note = () => txt('recentre-note');
  const btnDisabled = () => E(() => document.getElementById('recentre').disabled);
  const P = () => E(() => window.__peers.length);
  const frame = (extra) => E((x) => { const p = window.__peers.at(-1); const c = p.conns.at(-1); c.emit('data', JSON.stringify(Object.assign({ head: { px: 0, py: 1.2, pz: 0, qx: 0, qy: 0, qz: 0, qw: 1 }, left: null, right: null, leftValid: false, rightValid: false, activeSphere: 2, radius: 0.45, height: 1.2, score: 5, condition: 1, dominantHand: 'LEFT', fireMode: false, isPaused: false, trialCount: 3, totalTrials: 352, homePos: { x: 0, y: 0.9, z: -0.4 } }, x))); }, extra || {});
  const sent = () => E(() => window.__peers.flatMap(p => p.conns.flatMap(c => c.sent.map(s => JSON.parse(s)))).map(d => d.code || d.type));
  const count = async (code) => (await sent()).filter(c => c === code).length;
  const isOpen = (id) => E((i) => document.getElementById(i).classList.contains('open'), id);

  console.log('OBSERVER (Chromium)');
  ok(await E(() => !!document.querySelector('canvas') && window.__obs && window.__obs.frames > 0), 'three.js canvas rendering');
  ok(await P() === 1, 'peer created on load');
  ok((await st()) === 'Connecting', 'top bar starts at "Connecting"');
  ok(await btnDisabled(), 'recentre disabled before connection');
  await E(() => window.__peers[0].serverOpen());
  ok(await E(() => window.__peers[0].conns.length === 1 && window.__peers[0].conns[0].peer === 'webspheres-host'), 'connects to webspheres-host once peer opens');
  await E(() => window.__peers[0].emit('error', { type: 'peer-unavailable' }));
  ok((await st()) === 'Not found', 'peer-unavailable → "Not found"');
  await page.clock.runFor(3100);
  ok(await E(() => window.__peers[0].conns.length === 2 && window.__peers[0].conns[0].closed), 'retries after 3 s, old attempt closed');

  await E(() => { const c = window.__peers[0].conns.at(-1); c.open = true; c.emit('open'); });
  await frame();
  ok((await st()) === 'Connected', 'connected status on open/data');
  ok(await E(() => getComputedStyle(document.getElementById('conn-dot')).backgroundColor === 'rgb(61, 220, 132)'), 'status dot green when connected');
  ok(!(await btnDisabled()), 'recentre enabled while live');
  await page.clock.runFor(2100);
  ok((await sent()).includes('ping'), 'heartbeat ping sent every 2 s');

  console.log(' top bar');
  await frame();
  ok((await txt('v-trial')) === '3 / 352' && (await txt('v-score')) === '5' && (await txt('v-cond')) === 'NO-MANIP' && (await txt('v-dom')) === 'L' && (await txt('v-fire')) === '–', 'trial, score, condition, dominant, fire shown');
  await frame({ condition: 2, dominantHand: 'RIGHT', fireMode: true, score: 84, trialCount: 12 });
  ok((await txt('v-trial')) === '12 / 352' && (await txt('v-score')) === '84' && (await txt('v-cond')) === 'BOOST-TAX' && (await txt('v-dom')) === 'R', 'top bar follows new values');
  ok((await txt('v-fire')) === 'ON' && await E(() => getComputedStyle(document.getElementById('v-fire')).color === 'rgb(255, 211, 77)'), 'fire mode "ON" in critical colour');
  ok(await E(() => parseFloat(getComputedStyle(document.getElementById('v-score')).fontSize) >= 26), 'top-bar values ≥ 26 px');

  console.log(' recentre');
  await frame();
  await page.click('#recentre');
  ok(await count('KeyR') === 1 && (await note()) === 'Recentring…', 'button → KeyR sent + "Recentring…"');
  ok(await E(() => document.activeElement === document.body || document.activeElement === null), 'button does not hold focus after click');
  await page.keyboard.press('Space'); await page.keyboard.press('Enter');
  ok(await count('KeyR') === 1 && (await sent()).includes('Space'), 'Space/Enter after click relay normally, no extra recentre');
  await E(() => window.__peers[0].conns.at(-1).emit('data', JSON.stringify({ type: 'recentre', ok: true, reason: '' })));
  ok((await note()).startsWith('Recentred ') && await E(() => document.getElementById('recentre-note').className === 'ok'), 'ok ack → "Recentred <time>" in green');
  await frame(); await page.keyboard.press('KeyR');
  ok(await count('KeyR') === 2 && (await note()) === 'Recentring…', 'R key follows same path as button');
  await E(() => window.__peers[0].conns.at(-1).emit('data', JSON.stringify({ type: 'recentre', ok: false, reason: 'Not in VR' })));
  ok((await note()) === 'Recentre failed: Not in VR', 'failure ack shows reason');
  await frame(); await page.click('#recentre'); await frame(); await page.clock.runFor(1000); await frame(); await page.clock.runFor(1000); await frame(); await page.clock.runFor(1000); await frame(); await page.clock.runFor(1100);
  ok((await note()) === 'No response from headset', 'no ack → "No response from headset" within 3–4 s');

  console.log(' key relay and panels');
  await frame();
  const before = (await sent()).length;
  await page.keyboard.press('KeyH'); await page.keyboard.press('Digit1');
  const after = (await sent()).slice(before);
  ok(after.join() === 'KeyH,Digit1', 'keys relayed to headset when relay On');
  await page.keyboard.press('Escape');
  ok(!(await sent()).includes('Escape'), 'Esc stays local (not relayed)');
  await E(() => { window.__obs.settings.keyRelay = false; });
  const b2 = (await sent()).length;
  await page.keyboard.press('KeyH'); await frame(); await page.keyboard.press('KeyR');
  ok((await sent()).slice(b2).join() === 'KeyR', 'relay Off: keys not sent, Recentre still works');
  await E(() => { window.__obs.settings.keyRelay = true; });
  await E(() => window.__peers[0].conns.at(-1).emit('data', JSON.stringify({ type: 'recentre', ok: true, reason: '' })));

  await page.click('#btn-settings'); await page.clock.runFor(300);
  ok(await isOpen('drawer-settings') && !(await isOpen('drawer-readouts')), 'Settings opens its drawer');
  await page.click('#btn-readouts'); await page.clock.runFor(300);
  ok(await isOpen('drawer-readouts') && !(await isOpen('drawer-settings')), 'only one drawer open at a time');
  await page.mouse.click(300, 400); await page.clock.runFor(100);
  ok(await isOpen('drawer-readouts'), 'clicking the 3D scene does not close the drawer');
  const b3 = (await sent()).length;
  await page.keyboard.press('Space');
  ok(await isOpen('drawer-readouts') && (await sent()).slice(b3).join() === 'Space', 'Space after a panel click relays, does not toggle the panel');
  await page.keyboard.press('Escape');
  ok(!(await isOpen('drawer-readouts')), 'Esc closes the drawer');
  await page.click('#btn-help');
  ok(await isOpen('help') && (await txt('help-keys')).includes('Calibrate reach'), '? opens the key-help overlay');
  await page.click('#btn-help');
  ok(!(await isOpen('help')), '? toggles it closed');
  await page.click('#btn-help'); await page.keyboard.press('Escape');
  ok(!(await isOpen('help')), 'Esc closes key help');
  await page.click('#btn-settings'); await page.clock.runFor(300); await page.click('#drawer-settings [data-close]'); await page.clock.runFor(300);
  ok(!(await isOpen('drawer-settings')), 'drawer Close button works');

  console.log(' stale data');
  await frame(); await page.clock.runFor(300);
  ok(await E(() => document.getElementById('data-age').hidden && !document.getElementById('stage').classList.contains('stale')), 'fresh data: no age shown, scene not dimmed');
  await page.clock.runFor(2000);
  ok(await E(() => !document.getElementById('data-age').hidden && document.getElementById('stage').classList.contains('stale')) && /^No data 2\.\d s$/.test(await txt('data-age-value')), 'data older than 1 s: "No data 2.x s" shown, scene dimmed (' + (await txt('data-age-value')) + ')');
  await frame(); await page.clock.runFor(100);
  ok(await E(() => document.getElementById('data-age').hidden && !document.getElementById('stage').classList.contains('stale')), 'new data clears the stale state');

  console.log(' layout');
  const lay = await E(() => { const r = (id) => document.getElementById(id).getBoundingClientRect(); return { top: r('topbar'), stage: r('stage'), bottom: r('bottombar'), sw: document.documentElement.scrollWidth, iw: innerWidth, rb: r('recentre'), cw: document.getElementById('scene').width }; });
  ok(lay.top.bottom <= lay.stage.top + 0.5 && lay.stage.bottom <= lay.bottom.top + 0.5 && lay.bottom.bottom <= 900.5, 'top bar, scene and bottom bar do not overlap');
  ok(lay.sw <= lay.iw, 'no horizontal scroll');
  ok(lay.rb.height >= 44, 'buttons at least 44 px tall');
  const w0 = await E(() => document.getElementById('stage').clientWidth);
  await E(() => window.__obs.setLeftSlot(true)); await page.clock.runFor(100);
  const open = await E(() => ({ w: document.getElementById('stage').clientWidth, slot: document.getElementById('left-slot').getBoundingClientRect().width, a: window.__obs.camera.aspect, h: document.getElementById('stage').clientHeight, sw: document.documentElement.scrollWidth }));
  ok(Math.abs(open.slot - 380) < 1 && Math.abs(w0 - open.w - 380) < 1, 'left slot opens to 380 px and the scene shrinks to fit');
  ok(Math.abs(open.a - open.w / open.h) < 1e-6 && open.sw <= 1440, '3D view re-projects for the narrower scene, no horizontal scroll');
  await E(() => window.__obs.setLeftSlot(false)); await page.clock.runFor(100);
  ok(await E((w) => document.getElementById('stage').clientWidth === w && !document.getElementById('left-slot').offsetWidth, w0), 'left slot collapses back (empty in Plan A)');

  await frame(); await E(() => { const c = window.__peers[0].conns.at(-1); c.emit('data', 'garbage{'); c.emit('data', 'null'); c.emit('data', JSON.stringify({ head: 'bad' })); });
  ok((await st()) === 'Connected', 'malformed payloads ignored, still connected');

  console.log(' signalling drop while streaming');
  await frame(); await E(() => window.__peers[0].socketDrop());
  await frame();
  ok((await st()) === 'Connected', 'live stream unaffected by signalling drop');
  await E(() => window.__peers[0].conns.at(-1).close());
  ok((await st()) === 'Reconnecting' && (await detail()) === 'Disconnected', 'conn close → "Reconnecting"');
  ok(await btnDisabled(), 'recentre disabled while disconnected');
  await page.keyboard.press('KeyR');
  ok((await note()) === 'Not connected', 'R while disconnected → "Not connected", nothing sent');
  await page.clock.runFor(3100);
  ok(await P() === 2 && await E(() => window.__peers[0].destroyed), 'rebuilt a fresh Peer (old one destroyed), no crash');
  await E(() => window.__peers[1].serverOpen());
  ok(await E(() => window.__peers[1].conns.length === 1), 'new peer connects to host');
  await E(() => { const c = window.__peers[1].conns[0]; c.open = true; c.emit('open'); });
  await frame();
  ok((await st()) === 'Connected', 'recovered to Connected');

  console.log(' watchdog');
  await page.clock.runFor(6200);
  ok((await st()) === 'Reconnecting', 'silent stream (host asleep) detected within 5–6 s: "' + (await detail()) + '"');
  ok(await E(() => window.__peers[1].conns[0].closed && window.__peers[1].conns.length === 2), 'stale conn closed, new attempt started');
  await page.clock.runFor(11200);
  ok(await E(() => window.__peers[1].conns.length >= 3), 'connect attempt that never opens times out → retry within 10–11 s');

  console.log(' other errors');
  await E(() => window.__peers.at(-1).emit('error', { type: 'server-error' }));
  ok((await st()) === 'Error' && (await detail()).includes('server-error'), 'non-peer-unavailable error → "Error" with type (' + (await detail()) + ')');
  ok(await E(() => getComputedStyle(document.getElementById('conn-dot')).backgroundColor === 'rgb(255, 92, 92)'), 'status dot red on error');
  await E(() => window.__peers.at(-1).destroy());
  ok(/Error|Reconnecting/.test(await st()), 'peer destroyed after the error → still reported (' + (await st()) + ')');
  const n0 = await P(); await page.clock.runFor(3100);
  ok(await P() === n0 + 1, 'destroyed peer → new Peer');
  await E(() => window.__peers.at(-1).emit('error', { type: 'network' }));
  await E(() => document.dispatchEvent(new Event('visibilitychange')));
  ok(await P() === n0 + 2, 'visibility restore retries immediately');
  await E(() => window.__peers.at(-1).emit('error', { type: 'network' }));
  await E(() => window.dispatchEvent(new Event('online')));
  ok(await P() === n0 + 3, 'online event retries immediately');

  ok(errs.length === 0, 'no uncaught page errors (' + errs.join(' | ') + ')');

  await browser.close();
  done();
})().catch(e => { console.error(e); process.exit(2); });
